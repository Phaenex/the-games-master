import { chromium } from 'playwright';
import { createServer } from 'http';
import { readFile } from 'fs/promises';
import { extname, join } from 'path';
const ROOT = process.cwd(), PORT = 3796;
const MIME = { '.html':'text/html','.js':'text/javascript','.json':'application/json','.glb':'model/gltf-binary','.gltf':'model/gltf+json','.bin':'application/octet-stream','.png':'image/png','.ogg':'audio/ogg' };
const server = createServer(async (req,res)=>{ try{ let p=decodeURIComponent(req.url.split('?')[0]); if(p==='/')p='/index.html'; const fp=join(ROOT,p); const buf=await readFile(fp); res.writeHead(200,{'Content-Type':MIME[extname(fp)]||'application/octet-stream'}); res.end(buf);}catch{res.writeHead(404);res.end('nf');} });
await new Promise(r=>server.listen(PORT,r));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport:{ width:800, height:600 } });
await page.goto(`http://localhost:${PORT}/The%20Games%20Master%20-%20Prologue.dc.html`,{ waitUntil:'load' });
await page.waitForFunction(()=>window.__GMC && window.__GMC.gateLeafL, null, { timeout:120000 });
const rot = ()=>page.evaluate(()=>({ L:+window.__GMC.gateLeafL.rotation.y.toFixed(4), R:+window.__GMC.gateLeafR.rotation.y.toFixed(4) }));
console.log('open      ', await rot());
await page.evaluate(()=>{ window.__GMC._passedGate=true; window.__GMC._gateLockFired=true; window.__GMC.triggerGateLock(); });
await page.waitForTimeout(120); console.log('t~120ms   ', await rot());
await page.waitForTimeout(180); console.log('t~300ms   ', await rot());
await page.waitForTimeout(120); console.log('t~420ms   ', await rot());
await page.waitForTimeout(400); console.log('settled   ', await rot());
await browser.close(); server.close();
